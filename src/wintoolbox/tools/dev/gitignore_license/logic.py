def compose_gitignore(selected_templates: List[str], custom_rules: str = "") -> str:
    """Combina múltiplos templates de .gitignore em um único arquivo estruturado."""
    sections = []

    for name in selected_templates:
        if name in GITIGNORE_TEMPLATES:
            content = GITIGNORE_TEMPLATES[name].strip()
            sections.append(f"# ==========================================\n# {name}\n# ==========================================\n{content}")

    if custom_rules.strip():
        sections.append(f"# ==========================================\n# Regras Personalizadas\n# ==========================================\n{custom_rules.strip()}")

    return "\n\n".join(sections) + "\n"


def generate_license(license_key: str, year: Optional[int] = None, holder: str = "Seu Nome") -> str:
    """Gera o texto completo da licença substituindo ano e titular dos direitos."""
    if year is None:
        year = datetime.datetime.now().year

    template = LICENSE_TEMPLATES.get(license_key, LICENSE_TEMPLATES["MIT"])
    return template.format(year=year, holder=holder.strip() or "Nome do Autor")
