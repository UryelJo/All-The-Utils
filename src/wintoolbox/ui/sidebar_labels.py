def get_sidebar_tool_label(tool: BaseTool) -> str:
    """
    Retorna o rótulo simplificado para exibição na barra lateral.
    Se a ferramenta não estiver no mapeamento, retorna o nome original.
    """
    short = SIDEBAR_SHORT_LABELS.get(tool.id)
    if short:
        return short
    return (getattr(tool, "name", "") or getattr(tool, "title", "") or tool.id).strip()

